/** برچسب‌های سند ورودی؛ برگشت از فروش و رسید تولید برچسب خود را دارند و هر نوع دیگر برچسب رسید خرید را */
export function stockInLabels(docType: string | null | undefined): StockInLabels {
  if (docType === 'return') return RETURN_LABELS;
  if (docType === 'production_receipt') return PRODUCTION_LABELS;
  return PURCHASE_LABELS;
}

